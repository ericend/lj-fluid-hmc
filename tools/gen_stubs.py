"""
Auto-generate lj_hmc/_core.pyi type stubs from the compiled Rust extension.

Usage (from anywhere, after ``maturin develop``):
    python tools/gen_stubs.py
"""

import inspect
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent  # repo root, one level above tools/
OUTPUT_PATH = ROOT / "lj_hmc" / "_core.pyi"

FALLBACK_SIGNATURE = "(*args: Any, **kwargs: Any) -> Any"


def generate_stubs() -> None:
    try:
        from lj_hmc import _core as engine
    except ImportError:
        print(
            "Error: Could not import 'lj_hmc._core'. Did you run 'maturin develop' first?",
            file=sys.stderr,
        )
        raise SystemExit(1) from None

    lines: list[str] = [
        '"""Type stubs for the compiled Rust engine extension.',
        "",
        "Auto-generated by tools/gen_stubs.py. Do not edit manually.",
        '"""',
        "",
        "from typing import Any",
        "",
    ]

    for name, obj in inspect.getmembers(object=engine):
        if name.startswith("_"):
            continue
        if inspect.isroutine(obj):
            try:
                signature = str(inspect.signature(obj))
            except (ValueError, TypeError):
                signature = FALLBACK_SIGNATURE

            doc = inspect.getdoc(obj)
            lines.append(f"def {name}{signature}:")
            if doc:
                lines.append('    """')
                for doc_line in doc.splitlines():
                    lines.append(f"    {doc_line}" if doc_line else "")
                lines.append('    """')
            lines.append("    ...\n")

    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_PATH.write_text(
        "\n".join(lines).rstrip() + "\n",
        encoding="utf-8",
        newline="\n",
    )
    print(f"Successfully generated stubs at: {OUTPUT_PATH}")


if __name__ == "__main__":
    generate_stubs()
